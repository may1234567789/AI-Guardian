from __future__ import annotations

from typing import Any, Optional

from pydantic import BaseModel, Field


class PromptScanRequest(BaseModel):
    prompt: str = Field(..., min_length=1, max_length=20000, description="User prompt to evaluate for injection or sensitive data.")
    user_context: str = Field(default="mock-user", max_length=128, description="Development-only mock identity string; not production authentication.")
    source: Optional[str] = Field(default=None, max_length=128, description="Originating client or application name.")
    scan_output: bool = Field(default=False, description="Whether to also scan AI output after the prompt is processed.")


class ActionCheckRequest(BaseModel):
    prompt: str = Field(..., min_length=1, max_length=20000, description="Prompt that the agent intends to process before taking the action.")
    proposed_action: str = Field(..., min_length=1, max_length=128, description="Action requested by the agent.")
    resource_context: Optional[dict] = Field(default=None, description="Resource metadata for the requested action.")
    user_context: str = Field(default="mock-user", max_length=128, description="Development-only mock user identity reference.")
    user_role: str = Field(..., min_length=1, max_length=32, description="Assigned role for authorization evaluation.")
    confirm_delete: bool = Field(default=False, description="Explicit deletion confirmation required for destructive actions.")


class OutputScanRequest(BaseModel):
    output_text: str = Field(..., min_length=1, max_length=20000, description="Content generated by an AI agent that should be scanned before delivery.")
    source: Optional[str] = Field(default=None, max_length=128, description="Source of the AI output.")


class DocumentScanRequest(BaseModel):
    document_text: str = Field(..., min_length=1, max_length=20000, description="Text extracted from an untrusted document.")
    filename: Optional[str] = Field(default=None, max_length=256, description="Optional filename for context only.")
